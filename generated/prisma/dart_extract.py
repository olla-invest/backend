def get_keywords(induty_code: str, corp_name: str) -> list[str]:
    """업종코드 기반 키워드 반환. 긴 코드 우선 매칭."""
    code = str(induty_code).strip()
    # 긴 코드부터 매칭 시도
    for length in [5, 4, 3, 2, 1]:
        prefix = code[:length]
        if prefix in KSIC_MAP:
            return KSIC_MAP[prefix]
    # 매칭 실패 시 기업명 기반 추론
    return infer_from_name(corp_name)


def infer_from_name(name: str) -> list[str]:
    """기업명에서 키워드 추론 (코드 매핑 실패 시 fallback)"""
    name_lower = name.lower()
    if any(k in name for k in ["바이오", "생명", "pharma", "Bio"]):
        return ["바이오", "의약품", "생명과학"]
    if any(k in name for k in ["증권", "투자", "자산", "금융"]):
        return ["금융투자", "자산운용", "증권"]
    if any(k in name for k in ["건설", "건축", "토건"]):
        return ["건설", "시공", "부동산개발"]
    if any(k in name for k in ["화학", "케미"]):
        return ["화학 제조", "정밀화학", "소재"]
    if any(k in name for k in ["반도체", "semiconductor"]):
        return ["반도체", "전자부품", "소자"]
    if any(k in name for k in ["소프트", "시스템", "IT", "테크", "넷"]):
        return ["소프트웨어", "IT 서비스", "시스템"]
    if any(k in name for k in ["통신", "네트워크"]):
        return ["통신서비스", "네트워크", "인프라"]
    if any(k in name for k in ["에너지", "전력", "발전"]):
        return ["에너지", "전력", "신재생에너지"]
    if any(k in name for k in ["물류", "운송", "택배"]):
        return ["물류", "운송", "공급망"]
    if any(k in name for k in ["식품", "푸드", "음식"]):
        return ["식품 제조", "가공식품", "유통"]
    if any(k in name for k in ["유통", "상사", "무역"]):
        return ["상품 유통", "도소매", "무역"]
    return ["제조업", "서비스", "사업다각화"]


def update_db(conn, stock_code: str, keywords: list[str]) -> bool:
    try:
        with conn.cursor() as cur:
            cur.execute(
                "UPDATE companies SET business_info=%s::jsonb, updated_at=NOW() "
                "WHERE stock_code=%s AND deleted_at IS NULL",
                (json.dumps(keywords, ensure_ascii=False), stock_code),
            )
            updated = cur.rowcount
        conn.commit()
        return updated > 0
    except Exception as e:
        conn.rollback()
        print(f"DB error ({stock_code}): {e}")
        return False


def main():
    raw_path = Path("dart_raw.json")
