    for i, corp in enumerate(corps, 1):
        stock_code = corp["stock_code"]
        corp_name  = corp["corp_name"]
        induty_code = corp.get("induty_code", "")

        keywords = get_keywords(induty_code, corp_name)
        updated  = update_db(conn, stock_code, keywords)

        if updated:
            ok += 1
        else:
            no_match += 1
        print(f"[{i}/{total}] {corp_name} ({stock_code}) code={induty_code} -> {keywords} {'OK' if updated else 'NO_MATCH'}")

    conn.close()
    print(f"\n[DONE] DB 업데이트 {ok}개 / no_match {no_match}개")


